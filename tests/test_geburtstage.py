def check(name, cond):
    global ok; ok = ok and bool(cond); print(('PASS ' if cond else 'FAIL ') + name)
T = datetime.date.today(); iso = lambda d: d.isoformat(); dd = lambda n: iso(T + datetime.timedelta(days=n))
def born(years, in_days):  # Geburtsdatum: wird in `in_days` Tagen `years` Jahre alt (29.2. wird auf 28.2. gelegt)
    t = T + datetime.timedelta(days=in_days)
    try: return iso(t.replace(year=t.year - years))
    except ValueError: return iso(t.replace(year=t.year - years, day=28))
